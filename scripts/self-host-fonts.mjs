// scripts/self-host-fonts.mjs
// Downloads the Google Fonts that the docs site demos use and serves them from our own server, so visitors'
// browsers never contact Google (privacy: no IP address sent to a third party, no consent needed).
// Map: font URL from src/css/config/omniacss.fonts.css -> Google CSS (woff2) -> keep useful subsets -> download -> public/css/oc-google-fonts.css
// Run once after changing the font list: "node scripts/self-host-fonts.mjs". The output in public/ is committed.
// sync-site.mjs then swaps the Google @import in css/omnia-site.css for this local file.
//
// Subsets: Latin, Latin Extended, math, symbols and emoji. The Japanese fonts (Noto Sans/Serif JP) come in
// ~120 slices per weight; they are left out and the demos fall back to the system's Japanese fonts.

import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";

const root = process.cwd();
const outDir = path.join(root, "public/fonts/google");
const cssOut = path.join(root, "public/css/oc-google-fonts.css");
const KEEP = /^(all|latin|latin-ext|math|symbols|emoji)$/;
const SKIP_FAMILY = /\bJP$/;

const source = await fs.readFile(path.join(root, "src/css/config/omniacss.fonts.css"), "utf8");
const url = source.match(/https:\/\/fonts\.googleapis\.com\/css2\?[^"')]+/)?.[0];
if (!url) throw new Error("No Google Fonts URL in src/css/config/omniacss.fonts.css");

// A current browser user agent makes Google answer with woff2 files and unicode-range slices.
const ua = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";
const css = await (await fetch(url, { headers: { "User-Agent": ua } })).text();

await fs.rm(outDir, { recursive: true, force: true });
await fs.mkdir(outDir, { recursive: true });

// Every @font-face, with the subset comment before it when Google sends one (single-file fonts have none).
const blocks = [...css.matchAll(/(?:\/\*\s*([^*]+?)\s*\*\/\s*)?(@font-face\s*{[^}]*})/g)].map(([, subset, block]) => [null, subset ?? "all", block]);
const out = [];
let bytes = 0;
const files = new Map(); // remote url -> local file name (weights of a variable font share one file)
for (const [, subset, block] of blocks) {
  const family = block.match(/font-family:\s*'([^']+)'/)[1];
  if (SKIP_FAMILY.test(family) || !KEEP.test(subset)) continue;
  const remote = block.match(/url\((https:[^)]+)\)/)[1];
  if (!files.has(remote)) {
    const buf = Buffer.from(await (await fetch(remote)).arrayBuffer());
    const name = `${family.toLowerCase().replace(/\W+/g, "-")}-${subset}-${crypto.createHash("sha1").update(remote).digest("hex").slice(0, 8)}.woff2`;
    await fs.writeFile(path.join(outDir, name), buf);
    files.set(remote, name);
    bytes += buf.length;
  }
  out.push(`/* ${family}, ${subset} */\n` + block.replace(remote, `../fonts/google/${files.get(remote)}`));
}

await fs.writeFile(cssOut, `/* Generated by scripts/self-host-fonts.mjs: Google Fonts served from this site (no request to Google). */\n${out.join("\n")}\n`);
console.log(`[fonts] ${out.length} @font-face rules, ${files.size} files (${(bytes / 1024 / 1024).toFixed(1)} MB) → public/fonts/google, public/css/oc-google-fonts.css`);
