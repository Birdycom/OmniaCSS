// File: apps/docs/scripts/routes.mjs
// Generates one tiny Astro route per content file, so every page keeps its exact URL
// (docs/shapes/index.html, docs/borders/corner-shape.html, ui/components/card.html, …).
// Run automatically before "astro dev" and "astro build". Output: src/pages/** (generated, not committed).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.join(app, "src/content");
const pagesDir = path.join(app, "src/pages");

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith(".html")) out.push(p);
  }
  return out;
}

fs.rmSync(pagesDir, { recursive: true, force: true });
let count = 0;
for (const file of walk(contentDir)) {
  const route = path.relative(contentDir, file).split(path.sep).join("/");
  const stub = path.join(pagesDir, route.replace(/\.html$/, ".astro"));
  const up = path.relative(path.dirname(stub), path.join(app, "src")).split(path.sep).join("/") || ".";
  fs.mkdirSync(path.dirname(stub), { recursive: true });
  fs.writeFileSync(stub, `---
// Generated by scripts/routes.mjs — edit src/content/${route} instead.
import ContentPage from "${up}/layouts/ContentPage.astro";
import source from "${up}/content/${route}?raw";
---
<ContentPage source={source} route="${route}" />
`);
  count++;
}
console.log(`[routes] ${count} pages`);
