// File: packages/migrate/src/bootstrap/compat.mjs
// The small stylesheet that keeps the Bootstrap grid (container, row, col-*, offset-*, g-*, row-cols-*) and the few
// utilities without an OmniaCSS twin working, for exactly the classes a project uses. Colors are Omnia tokens.
// Map: media query per breakpoint -> grid rule per class -> utility rule per class -> sorted CSS
// Author: Serge Cools | Framework: OmniaCSS

import { BREAKPOINTS, CONTAINERS, OMNIA_BREAKPOINTS, utilityDecls } from "./rules.mjs";
import { bpVariant } from "./convert.mjs";

const SPACE = { 0: "0", 1: "0.25rem", 2: "0.5rem", 3: "1rem", 4: "1.5rem", 5: "3rem" };
const pct = (n, of) => `${+((n / of) * 100).toFixed(6)}%`;

/** min-width in rem for a Bootstrap breakpoint, following the chosen breakpoint mode. */
function minRem(bp, version, mode) {
  const px = BREAKPOINTS[version][bp];
  if (!px) return 0;
  if (mode === "exact") return px / 16;
  return OMNIA_BREAKPOINTS[bpVariant(bp, version, mode).slice(0, -1)] / 16;
}

/**
 * @param {Iterable<string>} gridClasses grid classes found in the project
 * @param {Iterable<string>} utilityClasses utilities without an OmniaCSS twin
 * @param {{ version: 3|4|5, breakpoints?: "omnia"|"exact" }} o
 */
export function compatCss(gridClasses, utilityClasses, { version: v, breakpoints: mode = "omnia" }) {
  const rules = []; // { at: rem, css }
  const add = (at, css) => rules.push({ at, css });
  const gutter = v === 3 ? "30px" : "1.5rem";
  const grid = new Set(gridClasses);
  let m;

  if ([...grid].some((c) => c.startsWith("container"))) {
    const list = [...grid].filter((c) => c.startsWith("container"));
    add(0, `${list.map((c) => "." + c).join(", ")} {\n  width: 100%;\n  margin-inline: auto;\n  padding-inline: calc(${gutter} * 0.5);\n  max-width: none;\n}`);
    for (const [bp, max] of Object.entries(CONTAINERS[v])) {
      const sel = list.filter((c) => c === "container" || (/^container-(sm|md|lg|xl|xxl)$/.test(c) && BREAKPOINTS[v][c.slice(10)] <= BREAKPOINTS[v][bp]));
      if (sel.length) add(minRem(bp, v, mode), `${sel.map((c) => "." + c).join(", ")} { max-width: ${max}px; }`);
    }
  }
  if (grid.has("row") || [...grid].some((c) => /^(col|offset|g|row-cols)/.test(c))) {
    add(0, `.row {\n  --oc-gutter-x: ${gutter};\n  --oc-gutter-y: 0;\n  display: flex;\n  flex-wrap: wrap;\n  margin-top: calc(-1 * var(--oc-gutter-y));\n  margin-inline: calc(-0.5 * var(--oc-gutter-x));\n}\n.row > * {\n  flex-shrink: 0;\n  width: 100%;\n  max-width: 100%;\n  padding-inline: calc(var(--oc-gutter-x) * 0.5);\n  margin-top: var(--oc-gutter-y);\n}`);
  }
  for (const c of grid) {
    // col, col-md, col-auto, col-md-auto
    if ((m = c.match(/^col(?:-(sm|md|lg|xl|xxl))?$/))) add(minRem(m[1], v, mode), `.${c} { flex: 1 0 0%; }`);
    else if ((m = c.match(/^col(?:-(sm|md|lg|xl|xxl))?-auto$/))) add(minRem(m[1], v, mode), `.${c} { flex: 0 0 auto; width: auto; }`);
    else if ((m = c.match(/^col(?:-(xs|sm|md|lg|xl|xxl))?-(\d{1,2})$/))) add(m[1] === "xs" ? 0 : minRem(m[1], v, mode), `.${c} { flex: 0 0 auto; width: ${pct(+m[2], 12)}; }`);
    else if ((m = c.match(/^offset(?:-(sm|md|lg|xl|xxl))?-(\d{1,2})$/)) || (m = c.match(/^col-(xs|sm|md|lg)-offset-(\d{1,2})$/))) add(m[1] === "xs" ? 0 : minRem(m[1], v, mode), `.${c} { margin-left: ${+m[2] ? pct(+m[2], 12) : "0"}; }`);
    else if ((m = c.match(/^col-(xs|sm|md|lg)-(push|pull)-(\d{1,2})$/))) add(m[1] === "xs" ? 0 : minRem(m[1], v, mode), `.${c} { position: relative; ${m[2] === "push" ? "left" : "right"}: ${pct(+m[3], 12)}; }`);
    else if ((m = c.match(/^row-cols(?:-(sm|md|lg|xl|xxl))?-(\d|auto)$/))) add(minRem(m[1], v, mode), `.${c} > * { flex: 0 0 auto; width: ${m[2] === "auto" ? "auto" : pct(1, +m[2])}; }`);
    else if ((m = c.match(/^g([xy]?)(?:-(sm|md|lg|xl|xxl))?-([0-5])$/))) {
      const vars = m[1] === "x" ? ["x"] : m[1] === "y" ? ["y"] : ["x", "y"];
      add(minRem(m[2], v, mode), `.${c} { ${vars.map((a) => `--oc-gutter-${a}: ${SPACE[m[3]]};`).join(" ")} }`);
    }
  }
  for (const c of utilityClasses) {
    let base = c, at = 0;
    if ((m = c.match(/^([a-z]+(?:-[a-z]+)*?)-(sm|md|lg|xl|xxl)-(.+)$/)) && BREAKPOINTS[v][m[2]]) { base = `${m[1]}-${m[3]}`; at = minRem(m[2], v, mode); }
    const groups = utilityDecls(base, v);
    if (groups) add(at, `.${c} { ${groups.flat().map((x) => x.replace(":", ": ") + ";").join(" ")} }`);
  }

  const byAt = new Map();
  for (const r of rules) byAt.set(r.at, [...(byAt.get(r.at) || []), r.css]);
  const out = [`/* Bootstrap ${v} compat for OmniaCSS — generated by omniacss-migrate (breakpoints: ${mode}).\n   Only the grid and the utilities without an OmniaCSS equivalent that this project uses. */`];
  for (const at of [...byAt.keys()].sort((a, b) => a - b)) {
    const body = byAt.get(at).join("\n");
    out.push(at ? `@media (min-width: ${at}rem) {\n${body.replace(/^/gm, "  ")}\n}` : body);
  }
  return out.join("\n\n") + "\n";
}
